def generate_face_features(n_samples=2000, seed=42):
    """
    Generate 64-dim face features matching inference-time extract_face_features() output.
    
    In extract_face_features():
      - 64 pixel values from 8x8 grayscale face crop, normalized 0..1
      - features[0] += anger_signal * 3.0  (dark mouth pixels)
      - features[6] += neutral_signal * 2.0 (for calm faces)
    
    Classes: ['Angry', 'Disgust', 'Fear', 'Happy', 'Sad', 'Surprise', 'Neutral']
    """
    np.random.seed(seed)
    EMOTION_CLASSES = ['Angry', 'Disgust', 'Fear', 'Happy', 'Sad', 'Surprise', 'Neutral']
    n_classes = len(EMOTION_CLASSES)
    
    # Base features: pixel intensities in [0.1, 0.9] range (like real face crops)
    X = np.random.uniform(0.1, 0.9, (n_samples, 64)).astype(np.float32)
    y = np.random.choice(n_classes, size=n_samples)
    
    for i in range(n_samples):
        cls = y[i]
        if cls == 0:  # Angry: dark mouth region (feat[0] boosted by anger_signal)
            X[i, 0] += np.random.uniform(2.0, 4.0)   # anger_signal * 3.0
            X[i, 1] += np.random.uniform(0.5, 1.5)   # disgust co-activation
            X[i, 6] -= np.random.uniform(0.1, 0.3)   # less neutral
        elif cls == 1:  # Disgust: subtle dark mouth + wrinkle patterns
            X[i, 1] += np.random.uniform(1.5, 3.5)
            X[i, 0] += np.random.uniform(0.3, 1.0)
        elif cls == 2:  # Fear: wide eyes (brighter), tense face
            X[i, 2] += np.random.uniform(1.8, 3.5)
            X[i, 3] += np.random.uniform(0.3, 0.8)   # slightly positive
            X[i, 6] -= np.random.uniform(0.2, 0.4)
        elif cls == 3:  # Happy: bright face, upturned corners
            X[i, 3] += np.random.uniform(2.0, 4.0)
            X[i, 5] += np.random.uniform(0.5, 1.5)   # surprise co-activation
            X[i, 6] += np.random.uniform(0.2, 0.5)   # also fairly neutral-like
        elif cls == 4:  # Sad: drooped features, dark regions
            X[i, 4] += np.random.uniform(2.0, 3.8)
            X[i, 2] += np.random.uniform(0.3, 1.0)   # fear similarity
            X[i, 0] -= np.random.uniform(0.0, 0.2)
        elif cls == 5:  # Surprise: raised eyebrows, wide mouth
            X[i, 5] += np.random.uniform(2.0, 4.0)
            X[i, 3] += np.random.uniform(0.5, 1.5)   # happy similarity
            X[i, 0] += np.random.uniform(0.3, 1.0)   # also some mouth opening
        else:  # Neutral: calm face, neutral signal boosted
            X[i, 6] += np.random.uniform(1.5, 3.5)   # neutral_signal * 2.0
            X[i, 3] += np.random.uniform(0.1, 0.5)   # slightly happy
            
    # Clip to realistic range (pixel features with emotion signals)
    X = np.clip(X, 0.0, 8.0).astype(np.float32)
    return X, y, EMOTION_CLASSES


def generate_pose_features(n_samples=2000, seed=42):
    """
    Generate 99-dim pose keypoint features matching inference-time extract_pose_features().
    
    In extract_pose_features():
      - MediaPipe returns normalized (x,y) in [0,1] and visibility in [0,1]
      - 33 keypoints * 3 = 99 features: [x0,y0,vis0, x1,y1,vis1, ...]
    
    Classes: ['Standing', 'Bending', 'Collapsed_Fall', 'Aggressive']
    """
    np.random.seed(seed)
    POSE_CLASSES = ['Standing', 'Bending', 'Collapsed_Fall', 'Aggressive']
    n_classes = len(POSE_CLASSES)
    
    X = np.zeros((n_samples, 99), dtype=np.float32)
    y = np.random.choice(n_classes, size=n_samples)
    
    for i in range(n_samples):
        cls = y[i]
        # Base: all keypoints with visibility ~0.9
        kp_x = np.random.uniform(0.3, 0.7, 33) + np.random.randn(33) * 0.05
        kp_y = np.linspace(0.05, 0.95, 33) + np.random.randn(33) * 0.05
        kp_v = np.random.uniform(0.8, 0.99, 33)
        
        if cls == 0:  # Standing: keypoints uniformly spread vertically
            kp_y = np.linspace(0.05, 0.95, 33)
            kp_x = np.random.uniform(0.4, 0.6, 33) + np.random.randn(33) * 0.03
            
        elif cls == 1:  # Bending: upper body tilted forward (torso keypoints low y)
            kp_y[:17] = np.random.uniform(0.6, 0.8, 17)  # torso bent forward
            kp_y[17:] = np.random.uniform(0.7, 0.9, 16)
            
        elif cls == 2:  # Collapsed/Fall: all keypoints at low y (ground level)
            kp_y = np.random.uniform(0.70, 0.95, 33)
            kp_x = np.random.uniform(0.1, 0.9, 33)  # sprawled out horizontally
            
        elif cls == 3:  # Aggressive: wrists high, shoulders spread wide
            kp_y[15] = np.random.uniform(0.01, 0.15)  # left wrist very high
            kp_y[16] = np.random.uniform(0.01, 0.15)  # right wrist very high
            kp_x[11] = np.random.uniform(0.05, 0.2)   # left shoulder spread left
            kp_x[12] = np.random.uniform(0.8, 0.95)   # right shoulder spread right
            kp_y[13] = np.random.uniform(0.05, 0.2)   # elbows raised
            kp_y[14] = np.random.uniform(0.05, 0.2)
        
        # Add realistic noise
        kp_x += np.random.randn(33) * 0.02
        kp_y += np.random.randn(33) * 0.02
        kp_x = np.clip(kp_x, 0.0, 1.0)
        kp_y = np.clip(kp_y, 0.0, 1.0)
        
        # Flatten to [x0,y0,vis0, x1,y1,vis1, ...]
        for j in range(33):
            X[i, j*3 + 0] = kp_x[j]
            X[i, j*3 + 1] = kp_y[j]
            X[i, j*3 + 2] = kp_v[j]
    
    return X.astype(np.float32), y, POSE_CLASSES


def generate_video_features(n_samples=1600, seq_len=16, feat_dim=128, seed=42):
    """
    Generate (n_samples, 16, 128) temporal features matching inference-time
    extract_video_features() output.
    
    In extract_video_features():
      - 8x8 blocks of grayscale frame, each contributing (mean, std) = 2 values
      - 8*8*2 = 128 features per frame
      - 16 frames per sequence
      - Anomaly classes have temporal spike in later frames
    
    Classes: ['Normal', 'Assault_Violence', 'Robbery', 'Abuse_Panic', 'Vandalism']
    """
    np.random.seed(seed)
    CRIME_CLASSES = ['Normal', 'Assault_Violence', 'Robbery', 'Abuse_Panic', 'Vandalism']
    n_classes = len(CRIME_CLASSES)
    
    X = np.zeros((n_samples, seq_len, feat_dim), dtype=np.float32)
    y = np.random.choice(n_classes, size=n_samples)
    
    for i in range(n_samples):
        cls = y[i]
        
        # Base: pixel block features. Mean ~0.3-0.5 (indoor scene), std ~0.05-0.15
        base_means = np.random.uniform(0.25, 0.55, (seq_len, feat_dim//2))
        base_stds  = np.random.uniform(0.03, 0.12, (seq_len, feat_dim//2))
        
        # Interleave means and stds to match [mean_b0, std_b0, mean_b1, std_b1, ...]
        seq = np.zeros((seq_len, feat_dim), dtype=np.float32)
        seq[:, 0::2] = base_means
        seq[:, 1::2] = base_stds
        
        if cls == 0:  # Normal: calm, stable spatial features
            # Slight variation across frames (natural scene motion)
            seq += np.random.randn(seq_len, feat_dim).astype(np.float32) * 0.02
            
        elif cls == 1:  # Assault/Violence: sudden motion spike, high std blocks
            spike_t = np.random.randint(5, 12)
            seq[spike_t:, 1::2] += np.random.uniform(0.15, 0.4, (seq_len-spike_t, feat_dim//2))
            seq[spike_t:, 0::2] += np.random.uniform(0.05, 0.2, (seq_len-spike_t, feat_dim//2))
            seq += np.random.randn(seq_len, feat_dim).astype(np.float32) * 0.05
            
        elif cls == 2:  # Robbery: rapid scene change mid-sequence
            t = np.random.randint(4, 8)
            seq[t:, :] = np.random.uniform(0.0, 0.8, (seq_len-t, feat_dim))
            seq[t:, 1::2] += np.random.uniform(0.10, 0.35, (seq_len-t, feat_dim//2))
            
        elif cls == 3:  # Panic/Abuse: erratic high variance throughout
            seq += np.random.uniform(0.05, 0.30, (seq_len, feat_dim)).astype(np.float32)
            seq[:, 1::2] += np.random.uniform(0.08, 0.25, (seq_len, feat_dim//2))
            
        elif cls == 4:  # Vandalism: gradual accumulation of scene disturbance
            for t in range(seq_len):
                ramp = t / seq_len
                seq[t, 1::2] += ramp * np.random.uniform(0.05, 0.30, feat_dim//2)
        
        X[i] = np.clip(seq, 0.0, 1.5)
    
    return X.astype(np.float32), y, CRIME_CLASSES


