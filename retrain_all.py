def train_face_branch(X, y, classes, epochs=120, lr=0.05):
    print(f"\n{DIVIDER}")
    print("  TRAINING FACIAL EXPRESSION BRANCH (inference-matched distribution)")
    print(DIVIDER)
    
    # Normalize
    mean = np.mean(X, axis=0, keepdims=True)
    std  = np.std(X, axis=0, keepdims=True) + 1e-8
    X_n  = (X - mean) / std
    
    n_classes = len(classes)
    np.random.seed(42)
    W_feat = np.random.randn(64, 64) * 0.15
    b_feat = np.zeros(64)
    W_cls  = np.random.randn(64, n_classes) * 0.15
    b_cls  = np.zeros(n_classes)
    
    one_hot = np.eye(n_classes)[y]
    best_acc = 0.0
    best_w   = None
    
    for epoch in range(1, epochs+1):
        h = np.maximum(0, X_n @ W_feat + b_feat)
        logits = h @ W_cls + b_cls
        exp_l  = np.exp(logits - np.max(logits, axis=-1, keepdims=True))
        probs  = exp_l / np.sum(exp_l, axis=-1, keepdims=True)
        
        loss = -np.mean(np.sum(one_hot * np.log(probs + 1e-8), axis=-1))
        acc  = np.mean(np.argmax(probs, axis=-1) == y)
        
        if acc > best_acc:
            best_acc = acc
            best_w   = (W_feat.copy(), b_feat.copy(), W_cls.copy(), b_cls.copy())
        
        d_logits = (probs - one_hot) / len(X)
        g_Wcls   = h.T @ d_logits
        g_bcls   = np.sum(d_logits, axis=0)
        g_h      = (d_logits @ W_cls.T) * (h > 0)
        g_Wf     = X_n.T @ g_h
        g_bf     = np.sum(g_h, axis=0)
        
        cur_lr   = lr * (0.97 ** (epoch // 15))
        W_cls   -= cur_lr * g_Wcls
        b_cls   -= cur_lr * g_bcls
        W_feat  -= cur_lr * g_Wf
        b_feat  -= cur_lr * g_bf
        
        if epoch % 30 == 0 or epoch == epochs:
            print(f"  Epoch [{epoch:03d}/{epochs}] Loss={loss:.4f} Acc={acc*100:.1f}% (Best={best_acc*100:.1f}%)")
    
    W_f, b_f, W_c, b_c = best_w
    np.savez("saved_models/facial_model_weights.npz",
             W_feat=W_f, b_feat=b_f, W_cls=W_c, b_cls=b_c,
             mean=mean, std=std)
    print(f"  Saved: facial_model_weights.npz (Best Acc={best_acc*100:.2f}%)")
    
    model = FacialExpressionCNN(input_dim=64, num_emotions=n_classes)
    model.set_weights(W_f, b_f, W_c, b_c)
    return model, mean, std, best_acc


def train_pose_branch(X, y, classes, epochs=120, lr=0.08):
    print(f"\n{DIVIDER}")
    print("  TRAINING BODY POSE BRANCH (inference-matched MediaPipe distribution)")
    print(DIVIDER)
    
    mean = np.mean(X, axis=0, keepdims=True)
    std  = np.std(X, axis=0, keepdims=True) + 1e-8
    X_n  = (X - mean) / std
    
    n_classes = len(classes)
    np.random.seed(42)
    W1 = np.random.randn(99, 64) * 0.12
    b1 = np.zeros(64)
    W2 = np.random.randn(64, n_classes) * 0.12
    b2 = np.zeros(n_classes)
    
    one_hot = np.eye(n_classes)[y]
    best_acc = 0.0
    best_w   = None
    
    for epoch in range(1, epochs+1):
        h = np.maximum(0, X_n @ W1 + b1)
        logits = h @ W2 + b2
        exp_l  = np.exp(logits - np.max(logits, axis=-1, keepdims=True))
        probs  = exp_l / np.sum(exp_l, axis=-1, keepdims=True)
        
        loss = -np.mean(np.sum(one_hot * np.log(probs + 1e-8), axis=-1))
        acc  = np.mean(np.argmax(probs, axis=-1) == y)
        
        if acc > best_acc:
            best_acc = acc
            best_w = (W1.copy(), b1.copy(), W2.copy(), b2.copy())
        
        d_logits = (probs - one_hot) / len(X)
        g_W2 = h.T @ d_logits
        g_b2 = np.sum(d_logits, axis=0)
        g_h  = (d_logits @ W2.T) * (h > 0)
        g_W1 = X_n.T @ g_h
        g_b1 = np.sum(g_h, axis=0)
        
        cur_lr = lr * (0.97 ** (epoch // 15))
        W1 -= cur_lr * g_W1; b1 -= cur_lr * g_b1
        W2 -= cur_lr * g_W2; b2 -= cur_lr * g_b2
        
        if epoch % 30 == 0 or epoch == epochs:
            print(f"  Epoch [{epoch:03d}/{epochs}] Loss={loss:.4f} Acc={acc*100:.1f}% (Best={best_acc*100:.1f}%)")
    
    W1_, b1_, W2_, b2_ = best_w
    np.savez("saved_models/pose_model_weights.npz",
             W1=W1_, b1=b1_, W2=W2_, b2=b2_, mean=mean, std=std)
    print(f"  Saved: pose_model_weights.npz (Best Acc={best_acc*100:.2f}%)")
    
    model = BodyPoseNetwork()
    model.set_weights(W1_, b1_, W2_, b2_)
    return model, mean, std, best_acc


def train_video_branch(X, y, classes, epochs=100, lr=0.06):
    print(f"\n{DIVIDER}")
    print("  TRAINING VIDEO TEMPORAL BRANCH (inference-matched block feature distribution)")
    print(DIVIDER)
    
    # Normalize: shape (n, 16, 128) -> compute mean/std per (16, 128) position
    mean = np.mean(X, axis=0, keepdims=True)   # (1, 16, 128)
    std  = np.std(X, axis=0, keepdims=True) + 1e-8
    X_n  = (X - mean) / std
    
    n_classes = len(classes)
    n_samples  = len(X)
    seq_len    = X.shape[1]
    feat_dim   = X.shape[2]
    hidden_dim = 64
    
    np.random.seed(42)
    W_x  = np.random.randn(feat_dim, hidden_dim) * 0.08
    W_h  = np.random.randn(hidden_dim, hidden_dim) * 0.08
    b_h  = np.zeros(hidden_dim)
    W_cls = np.random.randn(hidden_dim, n_classes) * 0.12
    b_cls = np.zeros(n_classes)
    
    one_hot = np.eye(n_classes)[y]
    best_acc = 0.0
    best_w   = None
    
    for epoch in range(1, epochs+1):
        # Mini-batch forward pass
        batch_size = min(128, n_samples)
        idx = np.random.choice(n_samples, batch_size, replace=False)
        Xb  = X_n[idx]
        yb  = y[idx]
        oh_b = one_hot[idx]
        
        # LSTM-like recurrent forward
        h_t = np.zeros((batch_size, hidden_dim))
        for t in range(seq_len):
            x_t = Xb[:, t, :]
            h_t = np.tanh(x_t @ W_x + h_t @ W_h + b_h)
        
        logits = h_t @ W_cls + b_cls
        exp_l  = np.exp(logits - np.max(logits, axis=-1, keepdims=True))
        probs  = exp_l / np.sum(exp_l, axis=-1, keepdims=True)
        
        loss = -np.mean(np.sum(oh_b * np.log(probs + 1e-8), axis=-1))
        acc  = np.mean(np.argmax(probs, axis=-1) == yb)
        
        # Evaluate on full set periodically
        if epoch % 25 == 0 or epoch == epochs:
            full_h = np.zeros((n_samples, hidden_dim))
            ht_ = np.zeros((n_samples, hidden_dim))
            for t in range(seq_len):
                xt_ = X_n[:, t, :]
                ht_ = np.tanh(xt_ @ W_x + ht_ @ W_h + b_h)
            full_logits = ht_ @ W_cls + b_cls
            full_probs  = np.exp(full_logits - np.max(full_logits, axis=-1, keepdims=True))
            full_probs /= np.sum(full_probs, axis=-1, keepdims=True)
            full_acc = np.mean(np.argmax(full_probs, axis=-1) == y)
            if full_acc > best_acc:
                best_acc = full_acc
                best_w = (W_x.copy(), W_h.copy(), b_h.copy(), W_cls.copy(), b_cls.copy())
            print(f"  Epoch [{epoch:03d}/{epochs}] BatchAcc={acc*100:.1f}% FullAcc={full_acc*100:.1f}% (Best={best_acc*100:.1f}%)")
        
        # Gradient step on batch
        d_l = (probs - oh_b) / batch_size
        g_Wcls = h_t.T @ d_l
        g_bcls = np.sum(d_l, axis=0)
        g_h_last = (d_l @ W_cls.T) * (1 - h_t**2)
        g_Wx  = Xb[:, -1, :].T @ g_h_last
        g_bh  = np.sum(g_h_last, axis=0)
        
        cur_lr = lr * (0.97 ** (epoch // 20))
        W_x   -= cur_lr * np.clip(g_Wx, -5, 5)
        b_h   -= cur_lr * np.clip(g_bh, -5, 5)
        W_cls -= cur_lr * np.clip(g_Wcls, -5, 5)
        b_cls -= cur_lr * np.clip(g_bcls, -5, 5)
    
    W_x_, W_h_, b_h_, Wc_, bc_ = best_w
    np.savez("saved_models/video_model_weights.npz",
             W_x=W_x_, W_h=W_h_, b_h=b_h_, W_cls=Wc_, b_cls=bc_, mean=mean, std=std)
    print(f"  Saved: video_model_weights.npz (Best Acc={best_acc*100:.2f}%)")
    
    model = VideoTemporalCNNLSTM()
    model.set_weights(W_x_, W_h_, b_h_, Wc_, bc_)
    return model, mean, std, best_acc


def train_fusion_model(face_net, face_mean, face_std,
                       pose_net, pose_mean, pose_std,
                       video_net, video_mean, video_std,
                       X_face, y_face,
                       X_pose, y_pose,
                       X_video, y_video,
                       epochs=400, lr=0.08):
    print(f"\n{DIVIDER}")
    print("  TRAINING CONTEXT-AWARE ATTENTION FUSION NETWORK")
    print(DIVIDER)
    
    ctx_net = ContextMetadataNetwork()
    
    n = min(len(X_face), len(X_pose), len(X_video))
    
    # Normalize inputs to branch models
    Xf_n = (X_face[:n] - face_mean) / face_std
    Xp_n = (X_pose[:n] - pose_mean) / pose_std
    Xv_n = (X_video[:n] - video_mean) / video_std
    
    # Compute branch embeddings (fixed, not retrained here)
    face_feats  = face_net.forward(Xf_n)['features']   # (n, 64)
    pose_feats  = pose_net.forward(Xp_n)['features']   # (n, 64)
    
    vid_feats = []
    for i in range(n):
        vo = video_net.forward(Xv_n[i])
        vid_feats.append(vo['features'])
    vid_feats = np.array(vid_feats)  # (n, 64)
    
    # Generate context metadata (realistic distribution)
    np.random.seed(42)
    ctx_meta = np.column_stack([
        np.random.randint(0, 6, n).astype(float),
        np.random.uniform(0, 24, n),
        np.random.uniform(0.05, 1.0, n),
        np.random.randint(0, 45, n).astype(float),
        np.random.uniform(0.2, 0.95, n)
    ])
    ctx_feats = ctx_net.forward(ctx_meta)['features']  # (n, 32)
    
    # Use UCF-crime labels mapped to 5 fusion categories
    # y_video: [0:Normal, 1:Assault, 2:Robbery, 3:Panic, 4:Vandalism]
    # fusion categories: [0:Normal, 1:Fall, 2:Fighting, 3:Panic, 4:Loitering]
    # Map: 0->0, 1->2(Fighting), 2->4(Loitering/Robbery), 3->3(Panic), 4->1(Fall/Vandalism)
    label_map = {0: 0, 1: 2, 2: 4, 3: 3, 4: 1}
    y_fusion = np.array([label_map[int(lbl)] for lbl in y_video[:n]])
    one_hot  = np.eye(5)[y_fusion]
    
    total_dim = 64 + 64 + 64 + 32  # = 224
    
    np.random.seed(42)
    W_attn = np.random.randn(total_dim, 4) * 0.15
    b_attn = np.zeros(4)
    W_cls  = np.random.randn(total_dim, 5) * 0.15
    b_cls  = np.zeros(5)
    
    # Adam optimizer
    mWc = np.zeros_like(W_cls);  vWc = np.zeros_like(W_cls)
    mbc = np.zeros_like(b_cls);  vbc = np.zeros_like(b_cls)
    beta1, beta2, eps = 0.9, 0.999, 1e-8
    
    best_acc = 0.0
    best_w   = None
    
    for epoch in range(1, epochs+1):
        # Attention forward
        concat = np.hstack([face_feats, pose_feats, vid_feats, ctx_feats])
        
        attn_logits  = concat @ W_attn + b_attn
        exp_attn     = np.exp(attn_logits - np.max(attn_logits, axis=-1, keepdims=True))
        attn_weights = exp_attn / np.sum(exp_attn, axis=-1, keepdims=True)
        
        attended = np.hstack([
            face_feats * attn_weights[:, 0:1],
            pose_feats * attn_weights[:, 1:2],
            vid_feats  * attn_weights[:, 2:3],
            ctx_feats  * attn_weights[:, 3:4]
        ])
        
        logits = attended @ W_cls + b_cls
        exp_l  = np.exp(logits - np.max(logits, axis=-1, keepdims=True))
        probs  = exp_l / np.sum(exp_l, axis=-1, keepdims=True)
        
        loss = -np.mean(np.sum(one_hot * np.log(probs + 1e-8), axis=-1))
        acc  = np.mean(np.argmax(probs, axis=-1) == y_fusion)
        
        if acc > best_acc:
            best_acc = acc
            best_w = (W_attn.copy(), b_attn.copy(), W_cls.copy(), b_cls.copy())
        
        d_l  = (probs - one_hot) / n
        gWc  = attended.T @ d_l
        gbc  = np.sum(d_l, axis=0)
        
        # Adam update for W_cls, b_cls
        t_adam = epoch
        mWc = beta1*mWc + (1-beta1)*gWc
        vWc = beta2*vWc + (1-beta2)*gWc**2
        mWc_h = mWc / (1-beta1**t_adam)
        vWc_h = vWc / (1-beta2**t_adam)
        W_cls -= (lr / (np.sqrt(vWc_h)+eps)) * mWc_h
        
        mbc = beta1*mbc + (1-beta1)*gbc
        vbc = beta2*vbc + (1-beta2)*gbc**2
        mbc_h = mbc / (1-beta1**t_adam)
        vbc_h = vbc / (1-beta2**t_adam)
        b_cls -= (lr / (np.sqrt(vbc_h)+eps)) * mbc_h
        
        if epoch % 100 == 0 or epoch == epochs:
            print(f"  Epoch [{epoch:04d}/{epochs}] Loss={loss:.4f} Acc={acc*100:.1f}% (Best={best_acc*100:.1f}%)")
    
    Wa_, ba_, Wc_, bc_ = best_w
    np.savez("saved_models/fusion_model_weights.npz",
             W_attn=Wa_, b_attn=ba_, W_cls=Wc_, b_cls=bc_)
    print(f"  Saved: fusion_model_weights.npz (Best Acc={best_acc*100:.2f}%)")
    return best_acc


